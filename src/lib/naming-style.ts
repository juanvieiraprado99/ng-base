/** A component generated by the project structure (layouts, landing page). */
export interface StructureComponent {
  /** Directory relative to the app dir, e.g. `layout/private`. */
  dir: string;
  /** File name without extension, e.g. `private.component` / `private-layout`. */
  base: string;
  className: string;
  /** Selector without prefix, e.g. `private` / `private-layout`. */
  selector: string;
}

export interface StructureNames {
  privateLayout: StructureComponent;
  publicLayout: StructureComponent;
  landingPage: StructureComponent;
}

export function structureNames(style: NamingStyle): StructureNames {
  if (style === "modern") {
    return {
      privateLayout: {
        dir: "layout/private",
        base: "private-layout",
        className: "PrivateLayout",
        selector: "private-layout",
      },
      publicLayout: {
        dir: "layout/public",
        base: "public-layout",
        className: "PublicLayout",
        selector: "public-layout",
      },
      landingPage: {
        dir: "pages/landing-page",
        base: "landing-page",
        className: "LandingPage",
        selector: "landing-page",
      },
    };
  }
  return {
    privateLayout: {
      dir: "layout/private",
      base: "private.component",
      className: "PrivateComponent",
      selector: "private",
    },
    publicLayout: {
      dir: "layout/public",
      base: "public.component",
      className: "PublicComponent",
      selector: "public",
    },
    landingPage: {
      dir: "pages/landing-page",
      base: "landing-page.component",
      className: "LandingPageComponent",
      selector: "landing-page",
    },
  };
}
