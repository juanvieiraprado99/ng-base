import path from "node:path";
import fse from "fs-extra";
import type { Workspace } from "./workspace.js";

/**
 * - `modern`   — Angular v20+ style guide ("intent over role"): `user-card.ts` /
 *                `class UserCard`, `auth-guard.ts`, `cache.model.ts`.
 * - `suffixed` — classic role suffixes: `user-card.component.ts` /
 *                `class UserCardComponent`, `auth.guard.ts`, `cache.interface.ts`.
 */
export type NamingStyle = "modern" | "suffixed";

export const NAMING_STYLES: NamingStyle[] = ["modern", "suffixed"];

export interface NamingDetection {
  style: NamingStyle;
  reason: string;
}

const SKIP_DIRS = new Set(["node_modules", "dist", ".angular", ".git"]);

/** True when any `*.component.ts` exists under `dir` (bounded walk). */
async function hasSuffixedComponents(dir: string, depth = 4): Promise<boolean> {
  if (depth < 0 || !(await fse.pathExists(dir))) return false;
  const entries = await fse.readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    if (e.isFile() && e.name.endsWith(".component.ts")) return true;
  }
  for (const e of entries) {
    if (e.isDirectory() && !SKIP_DIRS.has(e.name)) {
      if (await hasSuffixedComponents(path.join(dir, e.name), depth - 1)) {
        return true;
      }
    }
  }
  return false;
}

/**
 * Detect the naming convention of an existing project, in priority order:
 * 1. angular.json schematics `type: "component"` / `type: "service"` (what
 *    `ng update` to v20 adds to keep the old suffixes);
 * 2. existing files under the app dir (`*.component.ts` vs a suffixless `app.ts`);
 * 3. the Angular major version (≥ 20 → modern).
 */
export async function detectNamingStyle(
  cwd: string,
  ws: Workspace,
  angularMajor: number | null,
): Promise<NamingDetection> {
  const component = ws.schematics["@schematics/angular:component"];
  const service = ws.schematics["@schematics/angular:service"];
  if (component?.type === "component" || service?.type === "service") {
    return {
      style: "suffixed",
      reason: "angular.json schematics keep the role suffix (type)",
    };
  }

  const appDir = path.join(cwd, ws.appDir);
  if (await hasSuffixedComponents(appDir)) {
    return { style: "suffixed", reason: "project uses *.component.ts files" };
  }
  if (await fse.pathExists(path.join(appDir, "app.ts"))) {
    return { style: "modern", reason: "project uses suffixless app.ts" };
  }

  if (angularMajor !== null && angularMajor >= 20) {
    return { style: "modern", reason: `Angular ${angularMajor} default` };
  }
  return { style: "suffixed", reason: "pre-v20 Angular default" };
}

/** File names of init-generated core files, relative to `outputDir`. */
